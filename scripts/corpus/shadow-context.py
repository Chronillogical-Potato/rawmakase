#!/usr/bin/env python3
"""Regenerate the positive-Shadows scene-context calibration.

Input is anonymous measured scene statistics and squared gain errors, not pixels.
Each error curve evaluates the existing two-scale operator at key offsets -2..2 EV.
Choose the minimum with a weak zero-offset penalty: an unconstrained key is ambiguous
on flat parts of the response. Keep the measured gain curves themselves monotone.

  python3 scripts/corpus/shadow-context.py
  python3 scripts/corpus/shadow-context.py --check

To refresh observations, use scene-tone-local.py's scene input, base and regional
maps and its inverse-default-curve gain measurements against linear-profile Camera
Raw Shadows 0/+100 renders. `describe` below is the runtime's descriptor, including
its box approximation and border policy. Photos must use taps from the current
engine. Auto-black observations include the median Shadows gain moving the default
black key, as in CurveSet::for_image. data/shadow-context.json retains the offset loss curves for reproducibility
without committing private photos, filenames or proprietary profiles.
"""
import argparse
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'data/shadow-context.json'
OUTPUT = ROOT / 'crates/rawmakase-engine/src/develop/shadow_context_data.rs'


def describe(logs, box):
    """34 exposure-relative features; NumPy is needed only to measure new scenes."""
    import numpy as np
    key = np.log2(np.mean(2. ** logs))
    features = list(np.percentile(logs, [1, 10, 25, 50, 75, 90, 95, 99, 99.5, 99.9]) - key)
    for scale in [.005, .02, .08, .25]:
        sigma = scale * max(logs.shape)
        radius = max(1, int(math.floor(math.sqrt(4 * sigma * sigma + 1) / 2 + .5)))

        def blur(a):
            for _ in range(3):
                a = box(a, radius)
            return a

        light = np.log2(blur(2. ** logs))
        features.extend(.5 * (np.percentile(light, [10, 50, 90, 99]) - key))
        detail = logs - blur(logs)
        features.extend([.5 * np.mean(abs(detail)), .5 * np.std(detail)])
    return features


def generate(source):
    data = json.loads(source.read_text())
    assert data['schema'] == 1
    scenes = data['scenes']
    centres, offsets = [], []
    for scene in scenes:
        f, errors = scene['features'], scene['squared_error']
        assert len(f) == 34 and len(errors) == 161
        assert all(math.isfinite(v) for v in f + errors)
        assert all(v >= 0 for v in errors)
        candidates = [data['offset_min'] + i * data['offset_step'] for i in range(len(errors))]
        best = min(range(len(errors)), key=lambda i: errors[i] + data['penalty'] * candidates[i] ** 2)
        centres.append(f)
        offsets.append(candidates[best])

    def number(v):
        s = f'{v:.7g}'
        return s if '.' in s or 'e' in s else s + '.'

    text = '// Generated by scripts/corpus/shadow-context.py from data/shadow-context.json.\n'
    text += '// Anonymous measured scene statistics; no pixels or camera-specific selection.\n'
    text += '#[rustfmt::skip]\n'
    text += f'pub(super) static CENTRES: [[f32; 34]; {len(centres)}] = [\n'
    text += ''.join('    [' + ', '.join(map(number, row)) + '],\n' for row in centres)
    text += '];\n#[rustfmt::skip]\n'
    text += f'pub(super) const OFFSETS: [f32; {len(offsets)}] = [' + ', '.join(map(number, offsets)) + '];\n'
    return text


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = generate(SOURCE)
    if args.check:
        if OUTPUT.read_text() != text:
            raise SystemExit('Shadows context data is stale; run scripts/corpus/shadow-context.py')
    else:
        OUTPUT.write_text(text)


if __name__ == '__main__':
    main()
